const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const svg = name => '<svg class="social-icon" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true"><path d="' + BRANDS[name] + '"/></svg>';

hexo.extend.tag.register('social', function () {
  const s = (hexo.theme.config && hexo.theme.config.social) || {};
  const items = [];

  const qq = String(s.qq || '').trim();
  if (qq) {
    // 电脑端打开 QQ「添加好友」窗口；手机端由 main.js 换成 data-mobile-href，打开资料卡加好友
    const pc = 'tencent://AddContact/?fromId=45&amp;fromSubId=1&amp;subcmd=all&amp;uin=' + esc(qq);
    const mobile = 'mqqapi://card/show_pslcard?src_type=internal&amp;version=1&amp;card_type=person&amp;source=sharecard&amp;uin=' + esc(qq);
    items.push('<a class="social-link is-qq" href="' + pc + '" data-mobile-href="' + mobile + '" ' +
      'data-copy="' + esc(qq) + '" title="添加 QQ 好友（同时复制 QQ 号）">' +
      svg('qq') + '<span class="social-text"><b>QQ</b><small>' + esc(qq) + '</small></span></a>');
  }

  const uid = String(s.bilibili || '').trim();
  if (uid) {
    const label = s.bilibili_name ? '@' + s.bilibili_name : 'UID ' + uid;
    items.push('<a class="social-link is-bili" href="https://space.bilibili.com/' + esc(uid) + '" target="_blank" rel="noopener" title="打开我的 B站 个人空间">' +
      svg('bilibili') + '<span class="social-text"><b>哔哩哔哩</b><small>' + esc(label) + '</small></span></a>');
  }

  return items.length ? '<div class="social">' + items.join('') + '</div>' : '';
});
